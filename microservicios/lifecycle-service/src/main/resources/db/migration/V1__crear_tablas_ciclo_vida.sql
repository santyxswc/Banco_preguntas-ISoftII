-- Contexto de Ciclo de vida: estado actual de cada pregunta y resultado de las operaciones
-- asíncronas (envío a revisión). Antes vivían en memoria y se perdían al reiniciar el servicio.
CREATE TABLE question_state (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT       NOT NULL,
    state       VARCHAR(20)  NOT NULL,
    changed_at  TIMESTAMP    NOT NULL,
    changed_by  VARCHAR(200),
    message     VARCHAR(1000),
    CONSTRAINT uk_question_state_question UNIQUE (question_id)
);

CREATE TABLE operation_result (
    id           VARCHAR(64)  PRIMARY KEY,
    question_id  BIGINT,
    type         VARCHAR(50)  NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    message      VARCHAR(1000),
    created_at   TIMESTAMP    NOT NULL,
    completed_at TIMESTAMP
);

CREATE INDEX idx_operation_result_question ON operation_result (question_id);
