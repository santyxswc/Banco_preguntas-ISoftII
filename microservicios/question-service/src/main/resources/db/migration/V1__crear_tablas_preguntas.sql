CREATE TABLE question (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_context  VARCHAR(4000),
    statement         VARCHAR(2000) NOT NULL,
    correct_option_id VARCHAR(5),
    justification     VARCHAR(4000),
    bibliography      VARCHAR(1000),
    competency        VARCHAR(200),
    topic             VARCHAR(200),
    subtopic          VARCHAR(200),
    difficulty        VARCHAR(20),
    author_id         BIGINT        NOT NULL,
    status            VARCHAR(20)   NOT NULL,
    created_at        TIMESTAMP     NOT NULL,
    updated_at        TIMESTAMP     NOT NULL
);

CREATE INDEX idx_question_author ON question (author_id);
CREATE INDEX idx_question_competency ON question (competency);
CREATE INDEX idx_question_topic ON question (topic);

CREATE TABLE question_option (
    question_id  BIGINT        NOT NULL,
    option_order INTEGER       NOT NULL,
    option_id    VARCHAR(5)    NOT NULL,
    option_text  VARCHAR(1000) NOT NULL,
    PRIMARY KEY (question_id, option_order),
    CONSTRAINT fk_option_question FOREIGN KEY (question_id) REFERENCES question (id) ON DELETE CASCADE
);
